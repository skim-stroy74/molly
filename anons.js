/* ================= ОБЪЯВЛЕНИЕ ДЛЯ ГОСТЕЙ =================

   Плашка при входе на сайт: «31 декабря только по браслетам»,
   «сегодня закрытый формат», «концерт переносится на субботу».

   Зачем. Такое случается несколько раз в год, и сейчас об этом можно
   сказать только во ВКонтакте — а половина гостей приедет зря.

   КАК ВКЛЮЧИТЬ. Заполните три строки ниже и залейте файл на сайт.
   Пустой заголовок = объявление выключено, ничего не показывается.

   Дата окончания обязательна: объявление снимет себя само, и на сайте
   не останется висеть новогоднее поздравление до марта.
   ========================================================= */
(function () {
  'use strict';

  var ОБЪЯВЛЕНИЕ = {
    /* Заголовок. Пусто — плашки нет. */
    заголовок: '',

    /* Текст. Можно в несколько предложений. */
    текст: '',

    /* До какого числа показывать, включительно. Формат ГГГГ-ММ-ДД.
       Например '2026-12-31' — исчезнет сама 1 января. */
    до: '',

    /* Необязательно: кнопка. Оставьте пустым, если не нужна. */
    кнопка: '',
    ссылка: ''
  };

  /* ---------- дальше трогать не нужно ---------- */

  if (!ОБЪЯВЛЕНИЕ.заголовок || !ОБЪЯВЛЕНИЕ.до) return;

  /* просрочено — молчим */
  var части = ОБЪЯВЛЕНИЕ.до.split('-');
  var крайний = new Date(+части[0], +части[1] - 1, +части[2], 23, 59, 59);
  if (isNaN(крайний) || new Date() > крайний) return;

  /* показываем один раз в сутки: гость прочитал — не мозолим глаза.
     Ключ привязан к тексту, поэтому новое объявление покажется снова. */
  var КЛЮЧ = 'molly_anons';
  var отпечаток = ОБЪЯВЛЕНИЕ.заголовок + '|' + ОБЪЯВЛЕНИЕ.до;
  try {
    var было = JSON.parse(localStorage.getItem(КЛЮЧ) || '{}');
    if (было.что === отпечаток && Date.now() - было.когда < 24 * 60 * 60 * 1000) return;
  } catch (e) {}

  function запомнить() {
    try {
      localStorage.setItem(КЛЮЧ, JSON.stringify({ что: отпечаток, когда: Date.now() }));
    } catch (e) {}
  }

  function текстом(тег, класс, содержимое) {
    var el = document.createElement(тег);
    if (класс) el.className = класс;
    if (содержимое) el.textContent = содержимое;   /* именно текстом, не разметкой */
    return el;
  }

  function показать() {
    var фон = текстом('div', 'anons');
    var окно = текстом('div', 'anons-box');

    окно.appendChild(текстом('div', 'anons-eyebrow', 'Дорогие гости'));
    окно.appendChild(текстом('h3', null, ОБЪЯВЛЕНИЕ.заголовок));
    if (ОБЪЯВЛЕНИЕ.текст) окно.appendChild(текстом('p', null, ОБЪЯВЛЕНИЕ.текст));

    if (ОБЪЯВЛЕНИЕ.кнопка && ОБЪЯВЛЕНИЕ.ссылка) {
      var кн = текстом('a', 'btn btn-gold', ОБЪЯВЛЕНИЕ.кнопка);
      кн.href = ОБЪЯВЛЕНИЕ.ссылка;
      окно.appendChild(кн);
    }

    var закрыть = текстом('button', 'anons-x', '×');
    закрыть.type = 'button';
    закрыть.setAttribute('aria-label', 'Закрыть объявление');
    окно.appendChild(закрыть);

    фон.appendChild(окно);
    document.body.appendChild(фон);
    requestAnimationFrame(function () { фон.classList.add('on'); });

    function убрать() {
      фон.classList.remove('on');
      запомнить();
      setTimeout(function () { фон.remove(); }, 300);
      document.removeEventListener('keydown', поEscape);
    }
    function поEscape(e) { if (e.key === 'Escape') убрать(); }

    закрыть.addEventListener('click', убрать);
    фон.addEventListener('click', function (e) { if (e.target === фон) убрать(); });
    document.addEventListener('keydown', поEscape);
    закрыть.focus();
  }

  /* Ждём, пока гость разберётся с уведомлением о cookie: два окна
     одно поверх другого — верный способ, чтобы закрыли оба не глядя. */
  function решилПроCookie() {
    /* Смотрим не на баннер, а на сохранённое решение: баннер появляется
       не сразу, и объявление успевало выскочить раньше него. */
    try { return !!localStorage.getItem('molly_cookie'); } catch (e) { return true; }
  }

  function дождатьсяОчереди() {
    if (решилПроCookie()) { setTimeout(показать, 900); return; }

    var ждём = 0;
    var таймер = setInterval(function () {
      if (решилПроCookie() || ждём > 120) {   /* минута ожидания — дальше показываем */
        clearInterval(таймер);
        setTimeout(показать, 700);
      }
      ждём++;
    }, 500);
  }

  /* даём странице встать на ноги, чтобы плашка не прыгала поверх загрузки */
  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', дождатьсяОчереди);
  } else {
    дождатьсяОчереди();
  }
})();
