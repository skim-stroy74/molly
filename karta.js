/* Карта Яндекса подгружается не сразу.

   Виджет ставит свои файлы cookie и сообщает Яндексу, что человек
   открыл нашу страницу. Грузить его до того, как посетитель ответил
   на баннер, — значит спрашивать разрешение задним числом: баннер
   висит, а данные уже ушли.

   Поэтому: согласился на cookie — карта появляется сама; отказался
   или ещё не ответил — на её месте адрес, ссылки на Яндекс Карты
   и 2ГИС и кнопка «Показать карту». Нажатие кнопки и есть согласие
   на этот один раз, выбор по cookie оно не меняет. */
(function () {
  var гнездо = document.getElementById('map');
  if (!гнездо) return;

  var адрес = гнездо.dataset.map;
  if (!адрес) return;

  var загружена = false;

  function загрузить() {
    if (загружена) return;
    загружена = true;
    var рамка = document.createElement('iframe');
    рамка.src = адрес;
    рамка.title = 'Карта: Магнитогорск, Завенягина, 8а';
    рамка.loading = 'lazy';
    гнездо.innerHTML = '';
    гнездо.appendChild(рамка);
  }

  function согласились() {
    try { return localStorage.getItem('molly_cookie') === 'yes'; } catch (e) { return false; }
  }

  if (согласились()) { загрузить(); return; }

  var кнопка = гнездо.querySelector('[data-map-go]');
  if (кнопка) кнопка.addEventListener('click', загрузить);

  /* Посетитель нажал «Принять» в баннере — показываем карту сразу,
     не заставляя жать ещё одну кнопку. */
  document.addEventListener('molly:cookie', function () {
    if (согласились()) загрузить();
  });
})();
